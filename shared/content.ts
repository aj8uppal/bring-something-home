export function isSafe(p: Vec, dimension: Dimension) {
  return dimension === 'wilds' && Math.hypot(p.x - HAVEN.x, p.z - HAVEN.z) < HAVEN.radius;
}
export function distance(a: Vec, b: Vec) {
  return Math.hypot(a.x - b.x, a.z - b.z);
}
