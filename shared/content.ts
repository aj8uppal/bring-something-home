/**
 * How a creature behaves between shots. The pattern stays one per creature so the bullets
 * remain readable; the behaviour is where the mastery lives, because it decides which
 * creature in a mixed pack you have to kill first.
 */
export type Behaviour =
  'charger' | 'kiter' | 'bulwark' | 'splitter' | 'summoner' | 'anchor' | 'lantern';
export interface EnemyDef {
  name: string;
  hp: number;
  damage: number;
  speed: number;
  radius: number;
  range: number;
  rate: number;
  xp: number;
  tier: number;
  pattern: 'aim' | 'fan' | 'ring' | 'spiral' | 'burst';
  color: string;
  boss?: boolean;
  elder?: boolean;
  behaviour?: Behaviour;
  /** What a splitter leaves behind when it dies. */
  splits?: { kind: string; count: number };
  /** What a summoner calls, how many it keeps alive, and how long between calls. */
  summons?: { kind: string; count: number; cooldown: number };
  /** Half-width of a bulwark's shielded front arc, in radians. Flank it or lose the damage. */
  guard?: number;
  /** A lantern's light: allies inside it fire faster, and a visible line says who. */
  aura?: { radius: number; rate: number };
  /** The range a kiter tries to hold, and the distance a charger commits from. */
  prefer?: number;
  /** How much of its own health a boss must lose during one windup for the attack to break. */
  breakPoint?: number;
  /** A boss's exposed core: shots landing outside this front arc hit it for more. */
  weak?: { arc: number; multiplier: number };
  /** Projectile family. Kept beside the creature so a new kind never edits the realm. */
  style?: number;
  /** The place this creature belongs to, for the bestiary and the atlas. */
  home?: string;
  lore: string;
}
